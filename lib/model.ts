// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and adds every other pre-token protocol the radar can rank: the
// early rows the radar exists to find. A protocol is pre-token when its
// record carries no token (no market cap, no CoinGecko id, no symbol). The
// snapshot's live-token protocols are kept apart and shown with the market's
// own values, never mixed into the ranked board.
//
// A protocol is rankable when it is pre-token and is not a wrapped, staked or
// bridged product of a token that already trades, not an exchange and not a
// versioned pool: the same exclusion the watchlist's own rule applies
// (category Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking or
// Restaked BTC, a name carrying a whole word wrapped, staked or staking, a
// name beginning with an exchange's name, a name ending in a version marker,
// or category CEX). The watchlist's 40 slugs are ranked whatever they are:
// the list is the floor and its coverage is never gambled.
//
// Implied value follows only from the snapshot's own figures, through five
// multipliers, all stated in the dashboard and recomputed by the page:
//
//   base        = tvl_usd x BASE_MULTIPLE
//   growthMult  = 1 + clamp(change_7d, -60, 120) / 100 x GROWTH_WEIGHT
//   maturityMult= 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   chainMult   = 1 + 0.04 x min(chains - 1, 5)            (multi-chain reach)
//   categoryMult= 0.9 + 0.2 x tokenizationRate(category)   (see below)
//   implied     = max(1, round(base x growthMult x maturityMult
//                               x chainMult x categoryMult))
//
// tokenizationRate(category) is computed from the snapshot itself, never
// from a hand-kept list: among the snapshot's protocols in that category,
// the share whose token already trades (live / (live + pre-token)). A
// category where most protocols already trade (Lending, Dexs) has proven
// token economics, so its pre-token members score a little higher; a
// category where almost none ever tokenized scores a little lower. A
// category with fewer than 5 protocols in the snapshot, or a null category,
// uses the neutral rate 0.5. No protocol name is ever special-cased: the
// same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

